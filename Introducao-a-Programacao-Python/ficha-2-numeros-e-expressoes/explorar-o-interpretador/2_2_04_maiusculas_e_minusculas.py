idade = 18
IDADE = 69

print(idade)           # 18
print(idade == IDADE)  # False

# Conclusão: Python distingue maiúsculas de minúsculas (case sensitive).
# 'idade' e 'IDADE' são nomes diferentes, associados a objetos diferentes.
